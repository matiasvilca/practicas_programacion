# Una aerolínea permite viajar con equipaje de mano hasta 8 kg. 
# Consigna: Pedir el peso del equipaje y mostrar si está permitido o no.

peso_equipaje = (float(input("Por favor, ingrese el peso de su equipaje: ")))
if peso_equipaje <= 8:
    print("Está permitido.")
else:
    peso_equipaje > 8 
    print("Peso excedido.")
    